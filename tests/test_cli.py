def test_explicit_config_flag(fake_home, repo_snippets, tmp_path, capsys):
    cfg_path = tmp_path / "alt.toml"
    cfg = Config(snippets=repo_snippets)
    cfg.outputs["neovim"].append(tmp_path / "tex.lua")
