def test_write_through_symlink_keeps_link(fake_home, repo_snippets):
    real_dir = fake_home / "dotfiles"
    real_dir.mkdir()
    (real_dir / "tex.lua").write_text("old")
    link_dir = fake_home / "nvim"
    link_dir.mkdir()
    link = link_dir / "tex.lua"
    link.symlink_to(real_dir / "tex.lua")
    cfg = Config(snippets=repo_snippets)
    cfg.outputs["neovim"].append(link)
    cfg.save()
    assert run("build") == 0
    assert link.is_symlink()
    assert (real_dir / "tex.lua").read_text().startswith("-- generated by snipsmith")


def test_dry_run_and_diff_report_without_writing(fake_home, repo_snippets, capsys):
    cfg = Config(snippets=repo_snippets)
    cfg.outputs["vscode"].append(fake_home / "x/latex.hsnips")
    cfg.save()
    assert run("build", "--dry-run") == 0
    assert "would write" in capsys.readouterr().out
    assert not (fake_home / "x/latex.hsnips").exists()
    assert run("build", "--diff") == 0
    assert "+++ " in capsys.readouterr().out
    assert not (fake_home / "x/latex.hsnips").exists()


def test_doctor_reports_missing_and_stale(fake_home, repo_snippets, capsys):
    cfg = Config(snippets=repo_snippets)
    cfg.outputs["neovim"] += [fake_home / "a/tex.lua", fake_home / "b/tex.lua"]
    cfg.save()
    (fake_home / "a").mkdir()
    (fake_home / "a/tex.lua").write_text("stale")
    assert run("doctor") == 1
    err = capsys.readouterr().err
    assert "stale ~/a/tex.lua" in err
    assert "missing ~/b/tex.lua" in err


def test_edit_rebuilds_and_reports_editor_failure(fake_home, repo_snippets, monkeypatch, capsys):
    cfg = Config(snippets=repo_snippets)
    cfg.outputs["neovim"].append(fake_home / "tex.lua")
    cfg.save()
    monkeypatch.delenv("VISUAL", raising=False)
    monkeypatch.setenv("EDITOR", "true")
    assert run("edit") == 0
    assert (fake_home / "tex.lua").exists()
    monkeypatch.setenv("EDITOR", "false")
    assert run("edit") == 1
    assert "exited with status 1" in capsys.readouterr().err


def test_clean_declined_and_nothing_to_clean(fake_home, repo_snippets, monkeypatch, capsys):
    cfg = Config(snippets=repo_snippets)
    cfg.outputs["neovim"].append(fake_home / "tex.lua")
    cfg.save()
    assert run("build") == 0
    monkeypatch.setattr("snipsmith.ui.confirm", lambda *a, **k: False)
    assert run("clean") == 0
    assert (fake_home / "tex.lua").exists()
    (fake_home / "tex.lua").unlink()
    assert run("clean") == 0
    assert "nothing to clean" in capsys.readouterr().out


