import pytest

from snipsmith.cli import main
from snipsmith.config import Config


def run(*argv):
    with pytest.raises(SystemExit) as info:
        main(list(argv))
    return info.value.code


def test_check_and_build_to_out_dir(fake_home, repo_snippets, tmp_path, capsys):
    assert run("check", str(repo_snippets)) == 0
    out = tmp_path / "out"
    assert run("build", str(repo_snippets), "--out", str(out)) == 0
    assert sorted(p.name for p in out.iterdir()) == [
        "latex.hsnips",
        "obsidian_snippets.js",
        "obsidian_variables.json",
        "tex.lua",
    ]
    assert run("build", str(repo_snippets), "--out", str(out)) == 0
    assert "4 files, 0 changed" in capsys.readouterr().out


def test_build_uses_config(fake_home, repo_snippets, capsys):
    cfg = Config(snippets=repo_snippets)
    cfg.outputs["neovim"].append(fake_home / "nvim/tex.lua")
    cfg.save()
    assert run("build") == 0
    assert (fake_home / "nvim/tex.lua").exists()
    assert run("build", "--diff") == 0
    assert "no changes" in capsys.readouterr().out
    assert run("doctor") == 0
    assert run("clean", "--yes") == 0
    assert not (fake_home / "nvim/tex.lua").exists()


